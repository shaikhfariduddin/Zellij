import { ZellijProject } from "@/types/blueprint";

function triggerDownload(content: string, filename: string, mimeType: string) {
  if (typeof window === "undefined") return;
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function exportToMarkdown(project: ZellijProject): void {
  const md = `
# ${project.name} — Product Requirements Document (PRD)
*Platform: ${project.targetPlatform} | Version: ${project.versionTag} | Build Readiness: ${project.testMatrix?.buildReadinessScore || 94}%*

---

## 1. Executive Summary & Problem Statement
${project.problemStatement || project.description}

### Target User Personas:
${project.targetPersonas
  ?.map(
    (p) => `- **${p.roleName}** (${p.technicalLevel}): ${p.painPoint}`
  )
  .join("\n")}

---

## 2. Module 1: Functional Requirements & User Stories
${project.requirements
  ?.map(
    (r) => `
### [${r.code}] ${r.title}
- **Priority:** ${r.priority} | **Category:** ${r.category} | **Persona:** ${r.userPersona}
- **Description:** ${r.description}
- **Acceptance Criteria:**
${r.acceptanceCriteria.map((ac) => `  - ${ac}`).join("\n")}
`
  )
  .join("\n")}

---

## 3. Module 2: Screen Blueprints & Sitemap
${project.screens
  ?.map(
    (s) => `
### [${s.code}] ${s.name} (\`${s.route}\`)
- **Access Level:** ${s.accessLevel} | **Layout:** ${s.layoutType}
- **Purpose:** ${s.purpose}
- **Components:**
${s.components.map((c) => `  - **${c.label}** (\`${c.type}\`): ${c.accessibleLabel}`).join("\n")}
`
  )
  .join("\n")}

---

## 4. Module 3: User Workflows
${project.workflows
  ?.map(
    (w) => `
### [${w.code}] ${w.name}
- **Actor:** ${w.userRole}
- **Goal:** ${w.goal}
- **Steps:**
${w.nodes.map((n, i) => `  ${i + 1}. [${n.type.toUpperCase()}] **${n.data.label}**: ${n.data.description}`).join("\n")}
- **Recovery Path:** ${w.recoveryPath}
`
  )
  .join("\n")}

---

## 5. Module 4: API Endpoints Catalog
${project.techSpec?.apiEndpoints
  ?.map(
    (api) => `
### \`${api.method} ${api.endpoint}\`
- **Summary:** ${api.summary}
- **Auth Required:** ${api.authenticated ? "Yes" : "No"} (${api.requiredRole})
- **Response Schema:** \`${api.responseSchema}\`
`
  )
  .join("\n")}

---

## 6. Module 5: Test Matrix
${project.testMatrix?.testCases
  ?.map(
    (tc) => `
### [${tc.code}] ${tc.title}
- **Mapped Requirement:** ${tc.requirementCode} | **Type:** ${tc.category}
- **Preconditions:** ${tc.preconditions}
- **Steps:**
${tc.steps.map((st) => `  - ${st}`).join("\n")}
- **Expected Result:** ${tc.expectedResult}
`
  )
  .join("\n")}

---
*Generated by Zellij — Turn an idea into architecture.*
`.trim();

  triggerDownload(md, `${project.slug}-PRD.md`, "text/markdown");
}

export function exportToPrisma(project: ZellijProject): void {
  const prismaSchema = `
// Prisma Schema for ${project.name}
// Generated by Zellij Architecture Platform

datasource db {
  provider = "postgresql"
  url      = env("DATABASE_URL")
}

generator client {
  provider = "prisma-client-js"
}

${project.techSpec?.databaseEntities
  ?.map(
    (entity) => `
model ${entity.tableName.charAt(0).toUpperCase() + entity.tableName.slice(1)} {
${entity.fields
  .map((f) => {
    let type = "String";
    if (f.type === "INTEGER") type = "Int";
    if (f.type === "BOOLEAN") type = "Boolean";
    if (f.type === "TIMESTAMPTZ") type = "DateTime";
    if (f.type === "JSONB") type = "Json";

    let attributes = "";
    if (f.isPrimaryKey) attributes += " @id @default(uuid())";
    if (f.isUnique && !f.isPrimaryKey) attributes += " @unique";
    if (f.name === "created_at" || f.name === "createdAt") attributes += " @default(now())";
    if (f.name === "updated_at" || f.name === "updatedAt") attributes += " @updatedAt";

    return `  ${f.name.padEnd(16)} ${type}${attributes}`;
  })
  .join("\n")}

  @@map("${entity.tableName}")
}
`
  )
  .join("\n")}
`.trim();

  triggerDownload(prismaSchema, "schema.prisma", "text/plain");
}

export function exportToOpenAPI(project: ZellijProject): void {
  const openapi = {
    openapi: "3.1.0",
    info: {
      title: project.name,
      description: project.description,
      version: project.versionTag || "1.0.0",
    },
    paths: Object.fromEntries(
      (project.techSpec?.apiEndpoints || []).map((api) => [
        api.endpoint,
        {
          [api.method.toLowerCase()]: {
            summary: api.summary,
            security: api.authenticated ? [{ bearerAuth: [] }] : [],
            responses: {
              "200": {
                description: "Success",
                content: {
                  "application/json": {
                    schema: { type: "object" },
                  },
                },
              },
            },
          },
        },
      ])
    ),
  };

  triggerDownload(JSON.stringify(openapi, null, 2), `${project.slug}-openapi.json`, "application/json");
}

export function exportToJSON(project: ZellijProject): void {
  triggerDownload(JSON.stringify(project, null, 2), `${project.slug}-blueprint.json`, "application/json");
}
